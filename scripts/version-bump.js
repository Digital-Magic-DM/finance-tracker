const fs = require('fs');
const path = require('path');

const packageJsonPath = path.resolve(__dirname, '../package.json');
const versionTsPath = path.resolve(__dirname, '../src/environments/version.ts');

// Read package.json
const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));

// Split version: major.minor.patch
let [major, minor, patch] = packageJson.version.split('.').map(Number);

// Increment patch
patch++;

const newVersion = `${major}.${minor}.${patch}`;

// Update package.json
packageJson.version = newVersion;
fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 2) + '\n');

// Create/Update version.ts
const versionContent = `// This file is automatically generated by scripts/version-bump.js
export const VERSION = '${newVersion}';
`;

// Ensure environments directory exists
const envDir = path.dirname(versionTsPath);
if (!fs.existsSync(envDir)) {
    fs.mkdirSync(envDir, { recursive: true });
}

fs.writeFileSync(versionTsPath, versionContent);

console.log(`Version bumped to ${newVersion}`);
